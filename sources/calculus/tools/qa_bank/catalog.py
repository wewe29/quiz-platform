_SECTION_PREFIX = "同济《高等数学》第七版 "


def _build_kp_index():
    idx = {}
    for key, text in SEC.items():
        ch = int(key.split(".")[0])
        section = text[len(_SECTION_PREFIX):] if text.startswith(_SECTION_PREFIX) else text
        # section 形如 "§3.3 泰勒公式"；label 取节次号之后的标题部分
        m = re.match(r"§\s*[\d.]+\s*(.*)$", section)
        label = (m.group(1) if m else section).strip()
        idx[key] = {
            "chapter": ch,
            "section": section,
            "label": label,
            "aliases": list(_ALIASES.get(key, [])),
        }
    return idx


KP_INDEX = _build_kp_index()

# 反查表：label -> [key]，供 resolve_kp 用
_LABEL_TO_KEYS = {}
for _k, _v in KP_INDEX.items():
    _LABEL_TO_KEYS.setdefault(_v["label"], []).append(_k)
    for _a in _v["aliases"]:
        _LABEL_TO_KEYS.setdefault(_a, []).append(_k)

# 别名 -> key 精确表
_ALIAS_TO_KEY = {}
for _k, _v in KP_INDEX.items():
    for _a in _v["aliases"]:
        _ALIAS_TO_KEY.setdefault(_a, _k)


def resolve_kp(text):
    """把自由文本归一到规范节次 key（形如 "3.3"）；无法归一时返回 None。

    归一顺序：
        1) 规范化后精确命中 key（"3.3" / "3.3 " / "§3.3"）
        2) 文本中抽出 "§X.Y" 或 "X.Y" 形式
        3) 命中节次标题（"泰勒公式"）
        4) 命中别名表（"洛必达法则"）

    **宁可归不上也不要瞎归**：写真题时如果知识点说不清，应该去查教材，
    而不是让归一函数猜一个。
    """
    if not text:
        return None
    s = str(text).strip()
    if s in SEC:
        return s
    norm = s.replace("§", "").replace(" ", "").replace("　", "")

    # 2) 抽出 X.Y 形式（带可选前缀词）
    m = re.search(r"(?<!\d)(\d{1,2})\.(\d{1,2})(?!\d)", norm)
    if m:
        k = "%s.%s" % (m.group(1), m.group(2))
        if k in SEC:
            return k

    # 3) 节次标题
    if norm in _LABEL_TO_KEYS:
        return _LABEL_TO_KEYS[norm][0]

    # 4) 别名
    if norm in _ALIAS_TO_KEY:
        return _ALIAS_TO_KEY[norm]

    # 5) 包含匹配（长别名优先，避免 "极限" 抢走 "重要极限"）
    for alias in sorted(_ALIAS_TO_KEY, key=len, reverse=True):
        if alias and alias in norm:
            return _ALIAS_TO_KEY[alias]
    return None


def kp_labels():
    """返回 (key, 显示标签) 的列表，按章、节序排列。供前端知识点筛选器用。"""
    out = []
    for ch in CHAPTERS:
        for sec in ch["secs"]:
            out.append((sec, KP_INDEX[sec]["label"]))
    return out
